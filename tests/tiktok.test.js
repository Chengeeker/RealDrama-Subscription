const assert = require('assert');
const fs = require('fs');
const path = require('path');
const vm = require('vm');
const context = vm.createContext({});
vm.runInContext(['sdk', 'tiktok'].map(name => fs.readFileSync(path.join(__dirname, '../programs', name + '.js'), 'utf8')).join('\n'), context);
const id = '6718335390845095173';
const row = (changes = {}) => ({video_id: id, duration: 10, title: 'Synthetic video', play: 'https://v16.tiktokcdn.com/video.mp4', author: {unique_id: 'example', nickname: 'Example'}, ...changes});
const reply = data => ({status: 200, text: JSON.stringify({code: 0, data})});
function start(action, input = {}, state = {}) { const gen = context.execute(action, input, state); return {gen, step: gen.next(), state}; }
let run = start('catalog');
assert.equal(new URL(run.step.value.url).pathname, '/api/feed/list/');
assert.equal(run.step.value.credential, false);
assert.equal(run.step.value.method, 'POST');
assert.equal(new URL(run.step.value.url).search, '');
assert.equal(new URLSearchParams(run.step.value.body).get('region'), 'US');
assert.match(run.step.value.headers['Content-Type'], /^application\/x-www-form-urlencoded/);
let step = run.gen.next(reply([row(), row(), row({video_id: '6718335390845095174', images: ['https://image.invalid/a.jpg']}), row({video_id: '6718335390845095175', play: 'https://127.0.0.1/private'}), row({video_id: '6718335390845095176', is_ad: true})]));
assert.equal(step.done, true); assert.equal(step.value.items.length, 1); assert.equal(step.value.hasMore, true);
const state = step.value.state;
run = start('catalog', {page: 2}, state);
step = run.gen.next(reply([row()])); assert.equal(step.done, false);
step = run.gen.next(reply([row()])); assert.equal(step.done, true); assert.equal(step.value.items.length, 0); assert.equal(step.value.hasMore, false);
run = start('search', {query: 'nature'});
assert.equal(new URL(run.step.value.url).pathname, '/api/feed/search/');
step = run.gen.next(reply({videos: [row()], cursor: '20', hasMore: true})); assert.equal(step.value.hasMore, true);
run = start('search', {query: 'nature', page: 2}, step.value.state);
assert.equal(new URLSearchParams(run.step.value.body).get('cursor'), '20');
step = run.gen.next(reply({videos: [row({video_id: '6718335390845095174'})], cursor: '20', hasMore: true})); assert.equal(step.value.hasMore, false);
run = start('detail', {drama: {sourceId: id}}, state);
assert.equal(run.step.done, true); assert.equal(run.step.value.chapters[0].id, id);
run = start('resolve', {drama: {sourceId: id}}, state);
assert.equal(run.step.done, true);
assert.equal(run.step.value.url, 'https://v16.tiktokcdn.com/video.mp4');
assert.equal(run.step.value.state.rows[id].play, '');
run = start('resolve', {drama: {sourceId: id}}, state);
assert.equal(new URLSearchParams(run.step.value.body).get('url'), id);
step = run.gen.next(reply(row({id, video_id: undefined, play: 'https://v16.tiktokcdn-us.com/fresh.mp4'})));
assert.equal(step.value.url, 'https://v16.tiktokcdn-us.com/fresh.mp4'); assert.equal(step.value.quality, 0); assert.equal(step.value.headers.Cookie, undefined);
run = start('resolve', {drama: {sourceId: id}});
assert.throws(() => run.gen.next(reply(row({video_id: '6718335390845095174'}))), /不可用/);
run = start('resolve', {drama: {sourceId: id}});
assert.throws(() => run.gen.next(reply(row({images: ['https://image.invalid/a.jpg']}))), /不可用/);
run = start('catalog'); assert.throws(() => run.gen.next({status: 200, text: '{"code":-1,"msg":"private detail"}'}), /暂不可用/);
run = start('catalog'); assert.throws(() => run.gen.next({status: 429, text: ''}), error => error.httpStatus === 429);
run = start('search', {query: 'https://www.tiktok.com/@example/video/' + id});
assert.equal(new URLSearchParams(run.step.value.body).get('url'), id);
assert.equal(context.ttQueryId('https://www.tiktok.com.evil/@example/video/' + id), '');
assert.equal(context.ttUrl('https://v16.tiktokcdn.com.evil/video.mp4'), '');
assert.equal(context.ttUrl('https://v16.tiktokcdn.com:443/video.mp4'), '');
assert.equal(context.ttUrl('https://user@v16.tiktokcdn.com/video.mp4'), '');
const capped = {};
for (let i = 0; i < 70; i++) context.ttRemember(capped, row({video_id: String(6718335390845000000n + BigInt(i))}));
assert.equal(Object.keys(capped.rows).length, 48);
console.log('TikTok checks passed: catalog, pagination, cache bounds, filtering, exact video refresh, credentials and URL boundaries');

run = start('resolve', {drama: {sourceId: id}});
const originalRequest = run.step.value.url;
const originalBody = run.step.value.body;
step = run.gen.next({status: 531, text: '{"code":-1}'});
assert.equal(step.value.url, originalRequest);
assert.equal(step.value.body, originalBody);
step = run.gen.next(reply(row())); assert.equal(step.done, true);
run = start('catalog'); run.gen.next({status: 531, text: ''});
assert.throws(() => run.gen.next({status: 531, text: ''}), error => error.httpStatus === 531);
console.log('TikTok temporary upstream error retry stays bounded and preserves target identity');

assert.throws(() => start('search', {query: 'nature', page: 2}), /分页已过期/);
run = start('search', {query: 'one'});
step = run.gen.next(reply({videos: [row()], cursor: '10', hasMore: true}));
const sharedState = step.value.state;
run = start('search', {query: 'two'}, sharedState);
step = run.gen.next(reply({videos: [row()], cursor: '20', hasMore: true}));
run = start('search', {query: 'one', page: 2}, sharedState);
assert.equal(new URLSearchParams(run.step.value.body).get('cursor'), '10');
console.log('TikTok search cursors stay isolated and lost state never restarts page two at page one');

const expired = {};
context.ttRemember(expired, row()); expired.rows[id].at = Date.now() - 120001;
run = start('resolve', {drama: {sourceId: id}}, expired);
assert.equal(run.step.done, false);
assert.equal(new URLSearchParams(run.step.value.body).get('url'), id);
run = start('detail', {drama: {sourceId: id, title: 'Saved video'}});
assert.equal(run.step.done, true); assert.equal(run.step.value.chapters[0].id, id);
console.log('Fresh feed media is used once; retry and expired media refresh the exact ID; saved metadata opens offline');
